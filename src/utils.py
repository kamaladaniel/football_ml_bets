def load_leagues_config(config_name: str = "leagues.yaml"):
    """Load leagues configuration from YAML (leagues.yaml or active_leagues.yaml)."""
    config_path = CONFIG_DIR / config_name
    with open(config_path, "r", encoding="utf-8") as f:
        return yaml.safe_load(f)


def get_enabled_leagues(config_name: str = "leagues.yaml"):
    """Return only enabled leagues from the given config file."""
    config = load_leagues_config(config_name)
    return [lg for lg in config["leagues"] if lg.get("enabled", True)]


def get_all_leagues(config_name: str = "leagues.yaml"):
    """Return every league listed in the config (enabled or not)."""
    config = load_leagues_config(config_name)
    return list(config.get("leagues", []))


def save_active_leagues(active_leagues: list, target_date: str = None):
    """
    Write / overwrite config/active_leagues.yaml with only the leagues
    that have matches on the given date. All of them are set enabled: true.
    """
    from datetime import datetime, timezone
    if target_date is None:
        target_date = datetime.now(timezone.utc).date().strftime("%Y-%m-%d")

    # Preserve settings from the master leagues.yaml when possible
    try:
        master = load_leagues_config("leagues.yaml")
        settings = master.get("settings", {})
    except Exception:
        settings = {
            "max_matches_per_league": 12,
            "min_history_matches": 120,
            "retrain_every_run": True,
            "model_type": "dixon_coles",
            "history_seasons": 4,
            "request_delay": 0.35,
        }

    # Clean entries for YAML (drop runtime-only keys)
    clean = []
    for lg in active_leagues:
        clean.append({
            "name": lg["name"],
            "id": lg["id"],
            "country": lg.get("country", ""),
            "slug": lg["slug"],
            "enabled": True,
            "today_fixtures": lg.get("today_fixtures", 0),
        })

    payload = {
        "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC"),
        "target_date": target_date,
        "note": "Auto-generated by main.py – only leagues that have fixtures TODAY. Do not edit by hand.",
        "leagues": clean,
        "settings": settings,
    }

    out_path = CONFIG_DIR / "active_leagues.yaml"
    with open(out_path, "w", encoding="utf-8") as f:
        yaml.dump(payload, f, default_flow_style=False, allow_unicode=True, sort_keys=False)

    print(f"  Wrote {len(clean)} active league(s) → {out_path}")
    return out_path


def normalize_team_name(name: str) -> str:
    """Normalize team names for matching."""
    name = str(name or "").strip().lower()
    name = unicodedata.normalize("NFKD", name)
    name = "".join(ch for ch in name if not unicodedata.combining(ch))
    name = name.replace("&", " and ")
    name = re.sub(r"[^a-z0-9]+", " ", name)
    tokens = name.split()

    club_tokens = {
        "fc", "cf", "cd", "ac", "sc", "afc", "cfc", "gd", "ud",
        "club", "clube", "ss", "as", "us", "ssc", "rcd", "rc"
    }
    while tokens and tokens[0] in club_tokens:
        tokens.pop(0)
    while tokens and tokens[-1] in club_tokens:
        tokens.pop()
    return " ".join(tokens)


def find_team_match(api_name: str, team_history: dict, aliases: dict = None):
    """Find best matching team name from history."""
    aliases = aliases or {}
    normalized_api = normalize_team_name(api_name)

    # Check aliases first
    for alias_key, target in aliases.items():
        if normalize_team_name(alias_key) == normalized_api:
            for team in team_history:
                if normalize_team_name(team) == normalize_team_name(target):
                    return team

    # Exact normalized match
    matches = [t for t in team_history if normalize_team_name(t) == normalized_api]
    if len(matches) == 1:
        return matches[0]
    if len(matches) > 1:
        return matches[0]  # take first if ambiguous

    # Fuzzy fallback
    all_names = list(team_history.keys())
    norm_map = {normalize_team_name(n): n for n in all_names}
    suggestions = get_close_matches(normalized_api, list(norm_map.keys()), n=1, cutoff=0.72)
    if suggestions:
        return norm_map[suggestions[0]]

    return None


