ODDS_MARKETS = {"H", "D", "A", "Over15", "Over25", "Under25", "Under35",
                "HomeOver15", "AwayOver15", "BTTS_Yes", "BTTS_No"}


def load_manual_odds(path=None):
    """
    Optional bookmaker odds you type in: data/odds.csv with columns
        Date,HomeTeam,AwayTeam,Market,Odds
    Market is one of H, D, A, Over15, Over25, Under25, Under35,
    HomeOver15, AwayOver15, BTTS_Yes, BTTS_No. Odds are decimal (e.g. 2.10).
    Returns {(date, norm_home, norm_away): {market: odds}}.
    """
    import pandas as pd
    path = Path(path) if path else DATA_DIR / "odds.csv"
    if not path.exists():
        return {}
    try:
        df = pd.read_csv(path)
    except Exception as e:
        print(f"  Could not read {path.name}: {e}")
        return {}
    out = {}
    for _, r in df.iterrows():
        market = str(r.get("Market", "")).strip()
        try:
            odds = float(r["Odds"])
        except Exception:
            continue
        if market not in ODDS_MARKETS or odds <= 1.0:
            continue
        date = str(pd.to_datetime(r["Date"], errors="coerce").date())
        key = (date, normalize_team_name(r["HomeTeam"]), normalize_team_name(r["AwayTeam"]))
        out.setdefault(key, {})[market] = odds
    print(f"  Loaded manual odds for {len(out)} match(es) from {path.name}")
    return out
